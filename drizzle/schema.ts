import { 
  int, 
  mysqlEnum, 
  mysqlTable, 
  text, 
  timestamp, 
  varchar,
  json,
  decimal,
  boolean,
  longtext
} from "drizzle-orm/mysql-core";

/**
 * Core user table backing auth flow.
 * Extended with role field for admin/user distinction.
 */
export const users = mysqlTable("users", {
  id: int("id").autoincrement().primaryKey(),
  openId: varchar("openId", { length: 64 }).notNull().unique(),
  name: text("name"),
  email: varchar("email", { length: 320 }),
  loginMethod: varchar("loginMethod", { length: 64 }),
  role: mysqlEnum("role", ["user", "admin"]).default("user").notNull(),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
  lastSignedIn: timestamp("lastSignedIn").defaultNow().notNull(),
});

export type User = typeof users.$inferSelect;
export type InsertUser = typeof users.$inferInsert;

/**
 * Audio files uploaded by admins
 * Stores metadata and cloud storage reference
 */
export const audioFiles = mysqlTable("audioFiles", {
  id: int("id").autoincrement().primaryKey(),
  uploaderId: int("uploaderId").notNull(), // references users.id
  fileName: varchar("fileName", { length: 255 }).notNull(),
  fileKey: varchar("fileKey", { length: 512 }).notNull(), // S3 storage key
  fileUrl: varchar("fileUrl", { length: 1024 }).notNull(), // S3 storage URL
  mimeType: varchar("mimeType", { length: 64 }).notNull(), // audio/mpeg, audio/wav, etc.
  fileSizeBytes: int("fileSizeBytes").notNull(),
  duration: int("duration"), // audio duration in seconds
  transcription: longtext("transcription"), // auto-generated transcription from Whisper
  modelName: varchar("modelName", { length: 255 }), // e.g., "Model A", "Model B"
  asrText: longtext("asrText"), // ASR transcribed text
  questionnaireId: int("questionnaireId"), // 音频直接归属的问卷(可为空,兼容旧记录);音频管理据此列出与配对
  groupLabel: varchar("groupLabel", { length: 255 }), // 管理员指定的组别(如"query1"),同组内不同模型两两配对
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type AudioFile = typeof audioFiles.$inferSelect;
export type InsertAudioFile = typeof audioFiles.$inferInsert;

/**
 * Evaluation questionnaires
 * Created by admins, published for users to answer
 */
export const questionnaires = mysqlTable("questionnaires", {
  id: int("id").autoincrement().primaryKey(),
  creatorId: int("creatorId").notNull(),
  audioFileId: int("audioFileId"),
  audioUrl: varchar("audioUrl", { length: 1024 }),
  title: varchar("title", { length: 255 }).notNull(),
  description: text("description"),
  evaluationCopywriting: longtext("evaluationCopywriting"),
  scoringStandard: longtext("scoringStandard"),
  sampleSize: int("sampleSize"), // 发放样本组数:每个答卷人随机抽取的 groupLabel 组数;null/<=0 表示发放全部组
  status: mysqlEnum("status", ["draft", "published", "offline"]).default("draft").notNull(),
  shareToken: varchar("shareToken", { length: 64 }).unique(),
  validFrom: timestamp("validFrom"),
  validUntil: timestamp("validUntil"),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
  publishedAt: timestamp("publishedAt"),
});

export type Questionnaire = typeof questionnaires.$inferSelect;
export type InsertQuestionnaire = typeof questionnaires.$inferInsert;

/**
 * Blind test pairs for comparison
 */
export const blindTestPairs = mysqlTable("blindTestPairs", {
  id: int("id").autoincrement().primaryKey(),
  questionnaireId: int("questionnaireId").notNull(), // references questionnaires.id
  leftAudioFileId: int("leftAudioFileId").notNull(), // references audioFiles.id
  rightAudioFileId: int("rightAudioFileId").notNull(), // references audioFiles.id
  pairIndex: int("pairIndex").notNull(), // order of the pair in the test
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type BlindTestPair = typeof blindTestPairs.$inferSelect;
export type InsertBlindTestPair = typeof blindTestPairs.$inferInsert;

/**
 * Question types for questionnaires
 * Generated by AI based on evaluation copywriting
 */
export const questions = mysqlTable("questions", {
  id: int("id").autoincrement().primaryKey(),
  questionnaireId: int("questionnaireId").notNull(), // references questionnaires.id
  questionType: mysqlEnum("questionType", ["single_choice", "multiple_choice", "subjective"]).notNull(),
  questionText: longtext("questionText").notNull(),
  orderIndex: int("orderIndex").notNull(), // display order
  // For single/multiple choice questions
  options: json("options"), // Array<{ id: string, text: string }>
  correctAnswers: json("correctAnswers"), // Array<string> - option IDs
  // For subjective questions
  scoringRubric: longtext("scoringRubric"), // AI评分标准
  maxScore: decimal("maxScore", { precision: 5, scale: 2 }).default("10"),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type Question = typeof questions.$inferSelect;
export type InsertQuestion = typeof questions.$inferInsert;

/**
 * User responses to questionnaires
 * Tracks submission status and timestamps
 */
export const responses = mysqlTable("responses", {
  id: int("id").autoincrement().primaryKey(),
  userId: int("userId"),
  questionnaireId: int("questionnaireId"), // Can be null for blind tests
  blindTestPairId: int("blindTestPairId"), // references blindTestPairs.id
  // Ensure either questionnaireId or blindTestPairId is set

  visitorIp: varchar("visitorIp", { length: 45 }),
  visitorToken: varchar("visitorToken", { length: 64 }), // 浏览器级稳定标识(localStorage UUID),用于区分同 IP 的不同访客
  visitorName: varchar("visitorName", { length: 255 }),
  sampledGroupLabels: json("sampledGroupLabels"), // 抽样发放:该答卷抽中的 groupLabel 数组(锚定每人固定子集);null 表示不抽样、发放全部
  status: mysqlEnum("status", ["in_progress", "submitted", "graded"]).default("in_progress").notNull(),
  totalScore: decimal("totalScore", { precision: 5, scale: 2 }),
  aiComments: longtext("aiComments"),
  startedAt: timestamp("startedAt").defaultNow().notNull(),
  submittedAt: timestamp("submittedAt"),
  gradedAt: timestamp("gradedAt"),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type Response = typeof responses.$inferSelect;
export type InsertResponse = typeof responses.$inferInsert;

/**
 * Individual answers to questions within a response
 */
export const answers = mysqlTable("answers", {
  id: int("id").autoincrement().primaryKey(),
  responseId: int("responseId").notNull(), // references responses.id
  questionId: int("questionId"), // references questions.id (for regular questionnaires)
  evaluationDimensionId: int("evaluationDimensionId"), // references evaluationDimensions.id (for blind tests)
  blindTestPairId: int("blindTestPairId"), // references blindTestPairs.id (for blind tests)
  // For single/multiple choice: JSON array of selected option IDs
  // For subjective: text content
  answerContent: longtext("answerContent"), // Can be null for blind test choices
  blindTestChoice: mysqlEnum("blindTestChoice", ["left_better", "same", "right_better"]), // For blind tests

  score: decimal("score", { precision: 5, scale: 2 }),
  feedback: longtext("feedback"), // AI feedback for this specific answer
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type Answer = typeof answers.$inferSelect;
export type InsertAnswer = typeof answers.$inferInsert;

